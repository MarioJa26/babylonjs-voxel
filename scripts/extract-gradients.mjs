// Extracts the FastNoiseLite gradient tables from the vendored TS source and
// emits them as an AssemblyScript source file (src/wasm/gradient_tables.ts).
//
// Run with: node scripts/extract-gradients.mjs
//
// The tables must stay byte-identical to the JS implementation, otherwise the
// wasm noise output diverges from the JS noise. Re-run whenever the vendored
// FastNoiseLite.ts is updated.

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const srcPath = join(
	root,
	"src/code/Generation/NoiseAndParameters/FastNoise/FastNoiseLite.ts",
);
const outPath = join(root, "src/code/wasm/gradient_tables.ts");

const source = readFileSync(srcPath, "utf8");

function extract(name) {
	const re = new RegExp(
		`private _${name} = new Float32Array\\(\\[([\\s\\S]*?)\\]\\);`,
	);
	const match = source.match(re);
	if (!match) throw new Error(`Could not find _${name} in ${srcPath}`);
	const floats = match[1]
		.split(",")
		.map((s) => s.trim())
		.filter((s) => s.length > 0)
		.map((s) => {
			const n = Number(s);
			if (!Number.isFinite(n)) throw new Error(`Bad float in ${name}: ${s}`);
			return n;
		});
	return { name, floats };
}

const tables = [extract("Gradients2D"), extract("Gradients3D")];

const parts = [
	"// AUTO-GENERATED by scripts/extract-gradients.mjs - DO NOT EDIT.",
	"// Mirror of FastNoiseLite's _Gradients2D/_Gradients3D tables (f32).",
	"",
];

for (const { name, floats } of tables) {
	parts.push(`export const ${name}: StaticArray<f32> = [`);
	for (let i = 0; i < floats.length; i += 8) {
		parts.push("\t" + floats.slice(i, i + 8).join(", ") + ",");
	}
	parts.push("];", "");
}

writeFileSync(outPath, parts.join("\n"), "utf8");
console.log(
	`Wrote ${outPath}: ${tables
		.map((t) => `${t.name}=${t.floats.length}`)
		.join(", ")}`,
);
